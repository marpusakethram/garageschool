<h2>Directors, observers, and duties</h2>
<p>A <strong>director</strong> votes. In the US, directors owe fiduciary duties to the company and its stockholders as a whole: a duty of care, meaning they make informed decisions, and a duty of loyalty, meaning they put the company's interests ahead of their own. An investor on a board wears two hats. Their fund wants the best return on its shares, while their duty as a director runs to all stockholders, including founders and employees who hold common stock.</p>
<p>These interests usually line up. They can split in a sale where preferred investors get paid and common holders get little, or in a down round that wipes out early holders. In those moments, directors should get legal advice, use independent directors, and document a fair process.</p>
<p>An <strong>observer</strong> attends meetings and receives materials but does not vote and does not carry the same duties. Many funds use observer seats for smaller investments, and junior investors often start as observers. Observers still have to keep information confidential and should speak with care, since everyone in the room knows which fund they represent.</p>
<div class="note"><p class="note-title">Not legal advice</p><p>Board duties depend on where the company is incorporated and the specific situation. This lesson explains the general shape; real decisions need a lawyer.</p></div>

