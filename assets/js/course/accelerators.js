<p>An accelerator is a fixed-length program, usually around three months, that takes in a group of early-stage companies at the same time, called a batch or cohort. It invests a set amount in each company in exchange for equity, gives founders advice, introductions, and a community of peers, and ends with a demo day where companies present to investors.</p>
